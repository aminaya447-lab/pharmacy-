def rep_expiring(before_date):
    """Comparison operator: batches that expire before a date."""
    return _all("""
        SELECT i.Inventory_ID, i.Batch_Number, m.Medicine_Name,
               i.Quantity, i.Expiry_Date, b.Branch_Name
        FROM dbo.Inventory AS i, dbo.Inventory_Medicine AS im,
             dbo.Medicine AS m, dbo.Branch AS b
        WHERE i.Inventory_ID = im.Inventory_ID
          AND im.Medicine_ID = m.Medicine_ID
          AND i.Branch_ID = b.Branch_ID
          AND i.Expiry_Date < ?
        ORDER BY i.Expiry_Date
    """, (before_date,))


def rep_medicines_above_average():
    """Scalar subquery in WHERE."""
    return _all("""
        SELECT Medicine_ID, Medicine_Name, Price
        FROM dbo.Medicine
        WHERE Price > (SELECT AVG(Price) FROM dbo.Medicine)
        ORDER BY Price DESC
    """)


def rep_medicines_never_purchased():
    """NOT IN subquery."""
    return _all("""
        SELECT Medicine_ID, Medicine_Name, Price
        FROM dbo.Medicine
        WHERE Medicine_ID NOT IN (SELECT Medicine_ID FROM dbo.Purchase_Medicine)
        ORDER BY Medicine_ID
    """)


def rep_customers_without_sales():
    """NOT IN subquery."""
    return _all("""
        SELECT Customer_ID, Name, Phone
        FROM dbo.Customer
        WHERE Customer_ID NOT IN (SELECT Customer_ID FROM dbo.Sale)
        ORDER BY Customer_ID
    """)