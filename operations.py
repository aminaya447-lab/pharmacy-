def create_sale(customer_id, employee_id, payment, lines, doctor=None, diagnosis=None):
    """lines = {medicine_id: quantity}.
    Writes Sale, Sale_Medicine and (optionally) Prescription + Prescription_Sale.
    One transaction: if any step fails, nothing is saved.
    Returns (sale_id, amount)."""
    if not lines:
        raise ValueError("Add at least one medicine.")

    with get_cursor(commit=True) as cursor:
        total = Decimal("0")
        for mid, qty in lines.items():
            cursor.execute("SELECT Price FROM dbo.Medicine WHERE Medicine_ID = ?", (mid,))
            row = cursor.fetchone()
            if row is None:
                raise ValueError(f"Medicine {mid} does not exist.")
            total += row[0] * qty

        cursor.execute("""
            INSERT INTO dbo.Sale (Amount, Payment_Method, Customer_ID, Employee_ID)
            VALUES (?, ?, ?, ?)
        """, (total, payment, customer_id, employee_id))
        sale_id = _new_id(cursor)

        for mid, qty in lines.items():
            cursor.execute("""
                INSERT INTO dbo.Sale_Medicine (Sale_ID, Medicine_ID, Quantity)
                VALUES (?, ?, ?)
            """, (sale_id, mid, qty))

        if doctor:
            cursor.execute("""
                INSERT INTO dbo.Prescription (Doctor_Name, Diagnosis, Sale_ID)
                VALUES (?, ?, ?)
            """, (doctor, diagnosis, sale_id))
            presc_id = _new_id(cursor)
            cursor.execute("""
                INSERT INTO dbo.Prescription_Sale (Prescription_ID, Sale_ID)
                VALUES (?, ?)
            """, (presc_id, sale_id))

        return sale_id, float(total)


