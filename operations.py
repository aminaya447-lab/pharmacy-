def delete_sale(sale_id):
    """Prescription.Sale_ID is NO ACTION, so the prescriptions go first
    (their Prescription_Sale rows cascade); Sale_Medicine cascades from Sale."""
    with get_cursor(commit=True) as cursor:
        cursor.execute("DELETE FROM dbo.Prescription WHERE Sale_ID = ?", (sale_id,))
        cursor.execute("""
            DELETE FROM dbo.Prescription
            WHERE Prescription_ID IN
                  (SELECT Prescription_ID FROM dbo.Prescription_Sale WHERE Sale_ID = ?)
        """, (sale_id,))
        cursor.execute("DELETE FROM dbo.Sale WHERE Sale_ID = ?", (sale_id,))
        return cursor.rowcount


