from decimal import Decimal

from database import get_cursor


def _clean(rows):
    """Row -> tuple, Decimal -> float (so Streamlit shows numbers normally)."""
    return [
        tuple(float(v) if isinstance(v, Decimal) else v for v in row)
        for row in rows
    ]

def _all(sql, params=()):
    with get_cursor() as cursor:
        cursor.execute(sql, params)
        return _clean(cursor.fetchall())


def _one(sql, params=()):
    with get_cursor() as cursor:
        cursor.execute(sql, params)
        row = cursor.fetchone()
        return _clean([row])[0] if row else None


def _exec(sql, params=()):
    with get_cursor(commit=True) as cursor:
        cursor.execute(sql, params)
        return cursor.rowcount


def _new_id(cursor):
    """ID generated by the last INSERT (IDENTITY). Same connection, no triggers."""
    cursor.execute("SELECT @@IDENTITY")
    return int(cursor.fetchone()[0])


