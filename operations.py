    """Subquery in WHERE (book: subselect in WHERE and HAVING)."""
    sql = """
        SELECT p.ProductID, p.ProductName, p.Price
        FROM dbo.Products AS p
        WHERE p.Price > (SELECT AVG(Price) FROM dbo.Products)
        ORDER BY p.Price DESC
    """
